/** Nazwa kraju w języku sklepu (Intl), np. "NL" → "Holandia" / "Netherlands" / "Nederland". */
export function countryName(code: string, lang: ShopLang): string {
  try { return new Intl.DisplayNames([LOCALE[lang]], { type: "region" }).of(code) ?? code; } catch { return code; }
}
