/** Tłumaczenie gry: gt(language, key, {d:5}) → tekst z podstawionymi zmiennymi. */
export function gt(language: string, key: string, vars?: Record<string, string | number>): string {
  const lang: Lang = (["pl", "en", "nl", "ua"].includes(language) ? language : "en") as Lang;
  let s = STR[lang][key] ?? STR.en[key] ?? STR.pl[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}
